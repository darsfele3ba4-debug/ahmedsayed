// $...$  => معادلة تُكتب من اليمين لليسار كما في الكتاب
// {a/b}  => كسر رأسي (بسط فوق مقام)
// [[fig:f1]] => رسم هندسي من بيانات الدرس ، [[img:img/x.png]] => صورة
// الأرقام تُعرض كما فى الكتاب
function escapeHtml(s) {
    return String(s).replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;");
}
function fracify(s) {
    return s.replace(/\{([^{}\/]+)\/([^{}]+)\}/g, '<span class="frac"><span class="num">$1</span><span class="den">$2</span></span>');
}
const AR_DIGITS = "٠١٢٣٤٥٦٧٨٩";
function toAr(s) {
    return String(s); // الأرقام تظهر كما فى الكتاب (0123456789)
}
function figSvg(id) {
    const D0 = window.LESSON_DATA;
    return (D0 && D0.figs && D0.figs[id]) || '';
}
// كل تتابع لاتينى (أرقام + وحدات + رموز) يُعرض من اليسار لليمين وفى سطر واحد
const LTR_RUN = /[0-9A-Za-zΩθαΔπ°%√(][0-9A-Za-zΩθαΔπ°%.,:\/²³⁰¹⁴⁵⁶⁷⁸⁹⁻₀₁₂₃₄₅₆₇₈₉×÷≈+\-−=√()<>→ ]*[0-9A-Za-zΩθαΔπ°%²³⁰¹⁴⁵⁶⁷⁸⁹⁻₀₁₂₃₄₅₆₇₈₉)]|[0-9A-Za-zΩθαΔπ%]/g;
function fmt(raw) {
    const media = [];
    let s = String(raw).replace(/\[\[(fig|img):([^\]]+)\]\]/g, (m, k, v) => {
        media.push(k === 'fig' ? '<span class="m-fig">' + figSvg(v) + '</span>' : '<img class="m-img" src="' + escapeHtml(v) + '" alt="">');
        return String.fromCharCode(0xE000 + media.length - 1);
    });
    s = s.split(/(\$[^$]+\$)/).map(part => {
        if (/^\$[^$]+\$$/.test(part)) return '<span class="eq">' + fracify(escapeHtml(part.slice(1, -1))) + '</span>';
        return escapeHtml(part.replace(LTR_RUN, m => '\u0003' + m + '\u0004')).replace(/\u0003/g, '<span class="eq">').replace(/\u0004/g, '</span>');
    }).join('');
    return s.replace(/[\uE000-\uE0FF]/g, ch => media[ch.charCodeAt(0) - 0xE000]);
}
